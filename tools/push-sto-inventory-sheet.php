foreach ($rows as $r) {
  $printSum += is_numeric($r[5]) ? (float) $r[5] : 0;
  $factSum += is_numeric($r[6]) ? (float) $r[6] : 0;
  if ($r[7] === 'есть') {
    $found++;
  } else {
    $missing++;
  }
}

$extra = [
  [],
  ['Дополнительно с фото (не в печатной таблице)'],
  ['—', '—', '—', 'БАЛЛОНЧИК (?)', '—', '—', '—', 'рукопись', '', 'зачёркнуто, не читается'],
  ['—', '—', '—', 'ОСУШИТЕЛЬ', '—', '—', '—', 'рукопись', '', 'зачёркнуто'],
  ['—', '—', '—', 'Б/У предохр.', '—', '—', '1', 'рукопись', '', '«Б/У предохр. 1»'],
  [],
  ['Сводка OCR'],
  ['Позиций распознано', count($rows)],
  ['Есть на складе (факт > 0)', $found],
  ['Нет / 0 по инвентаризации', $missing],
  ['Сумма кол-во (печать)', $printSum],
  ['Сумма кол-во (факт OCR)', $factSum],
];

$outRows = array_map(static fn(array $r) => array_values($r), $rows);
$values = array_merge($header, $outRows, $extra);

$client = new Google_Client();
$client->setAuthConfig($credPath);
$client->setScopes([Google_Service_Sheets::SPREADSHEETS]);
$sheets = new Google_Service_Sheets($client);

$ss = $sheets->spreadsheets->get($spreadsheetId, ['fields' => 'properties.title,sheets.properties']);
$existingId = null;
foreach ($ss->getSheets() as $sh) {
  if ($sh->getProperties()->getTitle() === $sheetTitle) {
    $existingId = (int) $sh->getProperties()->getSheetId();
    break;
  }
}

$requests = [];
if ($existingId !== null) {
  $requests[] = ['deleteSheet' => ['sheetId' => $existingId]];
}
$requests[] = [
  'addSheet' => [
    'properties' => [
      'title' => $sheetTitle,
      'gridProperties' => [
        'rowCount' => max(120, count($values) + 10),
        'columnCount' => 12,
      ],
    ],
  ],
];

try {
  $resp = $sheets->spreadsheets->batchUpdate(
    $spreadsheetId,
    new Google_Service_Sheets_BatchUpdateSpreadsheetRequest(['requests' => $requests])
  );
} catch (Google\Service\Exception $e) {
  fwrite(STDERR, "Ошибка Google Sheets: " . $e->getMessage() . "\n");
  fwrite(STDERR, "Дайте Editor для pnevmopodveska1-bank@pnevmopodveska1.iam.gserviceaccount.com\n");
  exit(2);
}

$newSheetId = null;
foreach ($resp->getReplies() as $reply) {
  if ($reply->getAddSheet()) {
    $newSheetId = (int) $reply->getAddSheet()->getProperties()->getSheetId();
  }
}

$body = new Google_Service_Sheets_ValueRange([
  'range' => "'" . str_replace("'", "''", $sheetTitle) . "'!A1",
  'majorDimension' => 'ROWS',
  'values' => $values,
]);
$sheets->spreadsheets_values->update(
  $spreadsheetId,
  $body->getRange(),
  $body,
  ['valueInputOption' => 'USER_ENTERED']
);

$sheets->spreadsheets->batchUpdate(
  $spreadsheetId,
  new Google_Service_Sheets_BatchUpdateSpreadsheetRequest([
    'requests' => [
      [
        'updateSheetProperties' => [
          'properties' => [
            'sheetId' => $newSheetId,
            'gridProperties' => ['frozenRowCount' => 6],
          ],
          'fields' => 'gridProperties.frozenRowCount',
        ],
      ],
      [
        'repeatCell' => [
          'range' => [
            'sheetId' => $newSheetId,
            'startRowIndex' => 5,
            'endRowIndex' => 6,
            'startColumnIndex' => 0,
            'endColumnIndex' => 10,
          ],
          'cell' => [
            'userEnteredFormat' => [
              'textFormat' => ['bold' => true],
              'backgroundColor' => ['red' => 0.9, 'green' => 0.93, 'blue' => 0.98],
            ],
          ],
          'fields' => 'userEnteredFormat(textFormat,backgroundColor)',
        ],
      ],
    ],
  ])
);

$url = 'https://docs.google.com/spreadsheets/d/' . $spreadsheetId . '/edit#gid=' . $newSheetId;
echo "OK: {$sheetTitle}\n{$url}\n";
}
