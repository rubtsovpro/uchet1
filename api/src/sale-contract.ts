function buyerPreamble(buyer: ContractBuyer): string {
  if (buyerIsIp(buyer)) {
    const name = formatIpBuyerName(buyer);
    return `${esc(name)}, ИНН ${esc(blank(buyer.inn))}, ОГРНИП ${esc(blank(buyer.ogrn))}, действующий на основании сведений Единого государственного реестра индивидуальных предпринимателей (далее по тексту — Заказчик и/или Покупатель`;
  }
  const name = blank(buyer.name, 'Общество с ограниченной ответственностью «____________»');
  return `${esc(name)}, в лице ${esc(blank(buyer.director, 'Генерального директора ________________'))}, действующего на основании ${esc(blank(buyer.sign_basis, 'Устава'))} (далее по тексту — Заказчик и/или Покупатель`;
}

